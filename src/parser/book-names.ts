/**
 * Normalizes a book alias string for reliable matching:
 * - Lowercase
 * - Unifies apostrophes and removes dots/punctuation
 * - Splits joined leading book numbers like "1кор" -> "1 кор", "i кор" -> "1 кор"
 */
export function normalizeBookAlias(input: string): string {
  let s = input
    .trim()
    .toLowerCase()
    .replace(/['’ʼ`]/g, '')
    .replace(/\./g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  // Convert Roman numeral prefixes (I, II, III, IV or Ukrainian І, ІІ, ІІІ) if followed by space
  s = s
    .replace(/^(?:iii|ііі)\s+/, '3 ')
    .replace(/^(?:ii|іі)\s+/, '2 ')
    .replace(/^(?:iv|іv)\s+/, '4 ')
    .replace(/^(?:i|і)\s+/, '1 ');

  // Normalize "1-ша", "1-ше", "1-а", "1-е", "1ша", "2-га", "3-тя" or "1kor" -> "1 kor"
  s = s.replace(/^([1-4])\s*(?:-[а-яіїєґ]+|ша|ше|га|ге|тя|тє)?\s*([a-zа-яіїєґ])/i, '$1 $2');

  return s.replace(/\s+/g, ' ').trim();
}

const ALIAS_MAP = new Map<string, BookInfo>();
const NUMBER_MAP = new Map<number, BookInfo>();

// Alternate MyBible numbering (400..660 used in some Protestant modules)
const ALTERNATE_NT_NUMBER_MAP: Record<number, number> = {
  400: 470, // Matthew
  410: 480, // Mark
  420: 490, // Luke
  430: 500, // John
  440: 510, // Acts
  450: 590, // Romans
  460: 600, // 1 Cor
};

for (const book of BOOK_LIST) {
  NUMBER_MAP.set(book.bookNumber, book);

  const allNames = [
    book.canonicalCode,
    book.shortNameUa,
    book.longNameUa,
    book.shortNameEn,
    book.longNameEn,
    book.shortNameRu,
    book.longNameRu,
    ...book.aliases,
  ];

  for (const name of allNames) {
    const norm = normalizeBookAlias(name);
    if (norm && !ALIAS_MAP.has(norm)) {
      ALIAS_MAP.set(norm, book);
    }
    // Also register compact form without space after leading digit ("1 кор" -> "1кор")
    const compact = norm.replace(/^([1-4])\s+/, '$1');
    if (compact && !ALIAS_MAP.has(compact)) {
      ALIAS_MAP.set(compact, book);
    }
  }
}

export function findBookByAlias(input: string): BookInfo | undefined {
  const norm = normalizeBookAlias(input);
  if (!norm) return undefined;

  const exact = ALIAS_MAP.get(norm);
  if (exact) return exact;

  // Fallback prefix match if unambiguous or longest match
  for (const book of BOOK_LIST) {
    for (const alias of book.aliases) {
      const normAlias = normalizeBookAlias(alias);
      if (normAlias.startsWith(norm) && norm.length >= 2) {
        return book;
      }
    }
  }

  return undefined;
}

export function getBookByNumber(num: number): BookInfo | undefined {
  const direct = NUMBER_MAP.get(num);
  if (direct) return direct;

  const mappedNum = ALTERNATE_NT_NUMBER_MAP[num];
  if (mappedNum) {
    return NUMBER_MAP.get(mappedNum);
  }

  return undefined;
}
